import { $ } from "bun"
import { join } from "node:path"
import { tmpdir } from "node:os"
import { BrandGeometry } from "../src/assets/brand/geometry"
import { V2_AVATAR_LIGHT, V2_AVATAR_DARK } from "../src/theme/v2/avatar"

const root = join(import.meta.dir, "../../..")
const brand = join(root, "packages/ui/src/assets/brand")
const favicon = join(root, "packages/ui/src/assets/favicon")
const images = join(root, "packages/ui/src/assets/images")
const scratch = join(tmpdir(), `aigcfroge-brand-${process.pid}`)

// Static consumers cannot resolve CSS variables. Match the default v2 theme in sRGB.
export const colors = {
  light: {
    a: V2_AVATAR_LIGHT["v2-avatar-bg-blue"].slice(0, 7),
    g: V2_AVATAR_LIGHT["v2-avatar-bg-cyan"].slice(0, 7),
    dot: "#161616",
    contrast: "#ffffff",
    background: "#ffffff",
  },
  dark: {
    a: V2_AVATAR_DARK["v2-avatar-bg-blue"].slice(0, 7),
    g: V2_AVATAR_DARK["v2-avatar-bg-cyan"].slice(0, 7),
    dot: "#fafafa",
    contrast: "#ffffff",
    background: "#161616",
  },
}

export function baseColor(tone: keyof typeof colors) {
  return `#${[1, 3, 5]
    .map((offset) =>
      Math.round(
        Number.parseInt(colors[tone].g.slice(offset, offset + 2), 16) * 0.55 +
          Number.parseInt(colors[tone].contrast.slice(offset, offset + 2), 16) * 0.45,
      )
        .toString(16)
        .padStart(2, "0"),
    )
    .join("")}`
}

export function svg(size: number, tone: keyof typeof colors = "light", background = false) {
  const geometry = size <= 24 ? BrandGeometry.compact : BrandGeometry.full
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 100 100">
  <!-- Generated by packages/ui/script/generate-brand-assets.ts; v2 ${tone}, cyan 55% + text-contrast 45% in sRGB. -->
  ${background ? `<rect width="100" height="100" fill="${colors[tone].background}"/>` : ""}
  ${background ? '<g transform="translate(5 5) scale(.9)">' : ""}
  <polygon points="${geometry.a}" fill="${colors[tone].a}"/>
  <polygon points="${geometry.g}" fill="${colors[tone].g}"/>
  ${size > 24 ? `<circle cx="${BrandGeometry.full.dot.cx}" cy="${BrandGeometry.full.dot.cy}" r="${BrandGeometry.full.dot.r}" fill="${colors[tone].dot}"/>` : ""}
  ${size > 48 ? `<path d="${BrandGeometry.full.c}" fill="${baseColor(tone)}"/>` : ""}
  ${background ? "</g>" : ""}
</svg>\n`.replace(/^[ \t]+$/gm, "")
}

async function png(target: string, size: number, tone: keyof typeof colors = "light", background = false) {
  // Select geometry at the output size, then rasterize at 4x for antialiasing.
  await Bun.write(
    join(scratch, "render.svg"),
    svg(size, tone, background).replace(`width="${size}" height="${size}"`, `width="${size * 4}" height="${size * 4}"`),
  )
  await $`convert -background none ${join(scratch, "render.svg")} -resize ${`${size}x${size}`} -strip ${`PNG32:${target}`}`.quiet()
}

async function generate() {
  if (!Bun.which("convert")) throw new Error("ImageMagick convert is required")
  await $`python3 -c "from PIL import IcnsImagePlugin"`.quiet()
  await $`mkdir -p ${scratch} ${brand}`.quiet()
  try {
    await Bun.write(join(brand, "mark-master.svg"), svg(100))
    await Bun.write(join(brand, "mark-compact.svg"), svg(24))
    const adaptive = svg(24).replace(
      "<polygon",
      `<style>@media(prefers-color-scheme:dark){polygon:first-of-type{fill:${colors.dark.a}}polygon:last-of-type{fill:${colors.dark.g}}}</style>\n  <polygon`,
    )
    await Bun.write(join(favicon, "favicon.svg"), adaptive)
    await Bun.write(join(favicon, "favicon-v3.svg"), adaptive)
    await png(join(favicon, "favicon-96x96.png"), 96)
    await png(join(favicon, "apple-touch-icon.png"), 180, "light", true)
    await png(join(favicon, "web-app-manifest-192x192.png"), 192, "light", true)
    await png(join(favicon, "web-app-manifest-512x512.png"), 512, "light", true)
    await $`cp ${join(favicon, "favicon-96x96.png")} ${join(favicon, "favicon-96x96-v3.png")}`.quiet()
    await $`cp ${join(favicon, "apple-touch-icon.png")} ${join(favicon, "apple-touch-icon-v3.png")}`.quiet()
    const frames = await Promise.all(
      [16, 20, 24, 32, 48, 64, 128, 256].map(async (size) => {
        // Rasterization shares one temporary file, so each ICO frame has its own source.
        const source = join(scratch, `ico-${size}.svg`)
        const target = join(scratch, `ico-${size}.png`)
        await Bun.write(
          source,
          svg(size).replace(`width="${size}" height="${size}"`, `width="${size * 4}" height="${size * 4}"`),
        )
        await $`convert -background none ${source} -resize ${`${size}x${size}`} -strip ${`PNG32:${target}`}`.quiet()
        return target
      }),
    )
    await $`convert ${frames} ${join(favicon, "favicon.ico")}`.quiet()
    await $`cp ${join(favicon, "favicon.ico")} ${join(favicon, "favicon-v3.ico")}`.quiet()
    const manifest = await Bun.file(join(favicon, "site.webmanifest")).json()
    await Bun.write(
      join(favicon, "site.webmanifest"),
      JSON.stringify(
        {
          ...manifest,
          name: "AIGCFORGE",
          short_name: "AIGCFORGE",
          theme_color: colors.light.background,
          background_color: colors.light.background,
        },
        null,
        2,
      ) + "\n",
    )

    for (const channel of ["dev", "beta", "prod"]) {
      const directory = join(root, "packages/desktop/icons", channel)
      for (const entry of new Bun.Glob("*.png").scanSync(directory)) {
        const size =
          entry === "icon.png"
            ? 512
            : entry === "dock.png" || entry === "128x128@2x.png"
              ? 256
              : entry === "StoreLogo.png"
                ? 50
                : Number(entry.match(/\d+/)?.[0])
        if (!size) throw new Error(`Unknown icon size: ${entry}`)
        await png(join(directory, entry), size)
      }
      await $`cp ${join(favicon, "favicon.ico")} ${join(directory, "icon.ico")}`.quiet()
      await png(join(scratch, "1024.png"), 1024)
      // Pillow supplies the ICNS encoder; preserve size-specific geometry in its PNG entries.
      await $`python3 -c ${`from PIL import Image
import sys
from pathlib import Path
directory = Path(sys.argv[1])
image = Image.open(sys.argv[2])
image.save(directory / "icon.icns", append_images=[Image.open(directory / name) for name in ["32x32.png", "64x64.png", "128x128.png", "dock.png", "icon.png"]])`} ${directory} ${join(scratch, "1024.png")}`.quiet()
    }

    const logoSource = await Bun.file(join(root, "packages/ui/src/components/logo.tsx")).text()
    const wordmark = logoSource
      .slice(logoSource.indexOf("export const Logo"))
      .match(/<g fill="var\(--v2-text-text-base\)">([\s\S]*?)<\/svg>/)?.[1]
      .replace(/<\/g>\s*$/, "")
      .replace(/\{\/\*[\s\S]*?\*\/\}/g, "")
    if (!wordmark) throw new Error("Shared Logo geometry was not found")
    for (const [name, width, height, tone] of [
      ["social-share.png", 1280, 721, "light"],
      ["social-share-black.png", 1280, 721, "dark"],
      ["social-share-zen.png", 1200, 630, "light"],
    ] as const) {
      await Bun.write(
        join(scratch, "social.svg"),
        `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">
        <rect width="${width}" height="${height}" fill="${colors[tone].background}"/>
        <g transform="translate(${(width - 240) / 2} ${height / 2 - 184}) scale(2.4)">${svg(100, tone)
          .match(/<polygon[\s\S]*<\/svg>/)?.[0]
          .replace("</svg>", "")}</g>
        <g transform="translate(${(width - 489.6) / 2} ${height / 2 + 88}) scale(2.4)" fill="${colors[tone].dot}">${wordmark}</g>
      </svg>`,
      )
      await $`convert -background none ${join(scratch, "social.svg")} -strip ${`PNG32:${join(images, name)}`}`.quiet()
    }
    console.log("Generated scheme 04 Web and dev/beta/prod PNG/ICO/ICNS assets; mobile assets remain deferred.")
  } finally {
    await $`rm -rf ${scratch}`.quiet()
  }
}

if (import.meta.main) await generate()

export * as BrandAssets from "./generate-brand-assets"
